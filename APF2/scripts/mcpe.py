# Pesos de la MEFE y la MEFI del APF1. PA por estrategia: E1, E2, E4, E5, E7, E10
F = [
 ('O1',0.10,[3,4,2,1,2,3]),('O2',0.12,[4,3,2,3,3,3]),('O3',0.07,[3,2,2,1,2,4]),
 ('O4',0.08,[2,2,3,1,2,3]),('O5',0.08,[2,4,3,4,1,1]),
 ('A1',0.08,[2,3,2,1,2,4]),('A2',0.05,[2,1,1,3,2,2]),('A3',0.05,[3,2,1,2,2,2]),
 ('A4',0.08,[2,1,2,3,2,2]),('A5',0.15,[3,3,2,3,4,4]),('A6',0.14,[2,1,1,4,2,3]),
 ('F1',0.12,[4,3,2,3,4,2]),('F2',0.06,[3,3,2,2,4,2]),('F3',0.10,[3,4,2,3,2,3]),
 ('F4',0.08,[4,2,3,3,4,3]),('F5',0.06,[4,2,3,1,2,4]),('F6',0.06,[2,4,3,4,1,2]),
 ('D1',0.11,[2,1,1,4,2,3]),('D2',0.11,[1,1,1,4,1,2]),('D3',0.08,[2,1,1,4,1,2]),
 ('D4',0.09,[2,3,4,1,3,2]),('D5',0.08,[4,4,4,2,3,3]),('D6',0.05,[1,3,3,4,1,1]),
]
E = ['E1','E2','E4','E5','E7','E10']
assert abs(sum(w for _,w,_ in F)-2)<1e-9
for c,w,pa in F:
    assert len(set(pa))>1, c
if __name__ == '__main__':
    tot=[0]*6
    for c,w,pa in F:
        print(c, w, ' '.join(f'{p} {w*p:.2f}' for p in pa))
        for i,p in enumerate(pa): tot[i]+=w*p
    print('TOTAL', ' '.join(f'{e}={t:.2f}' for e,t in zip(E,tot)))
